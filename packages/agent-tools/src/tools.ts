/**
 * What an agent can do in Truman, once, for every way an agent works: the MCP server on a
 * researcher's computer, and "Draft from a brief" in the builder (ADRs 64 and 65). Each tool goes
 * through the admin API with a researcher's token, so the server's limits always apply.
 */

/** How Truman works and what an agent may do. Agents read it first. */
export const GUIDE = readFileSync(path.resolve(import.meta.dirname, "../guide.md"), "utf8");

export interface AgentTool<Shape extends z.ZodRawShape = z.ZodRawShape> {
  name: string;
  title: string;
  description: string;
  input: Shape;
  run: (client: TrumanClient, input: z.infer<z.ZodObject<Shape>>) => Promise<unknown>;
}

/** Keeps each tool's input typed where it's written, and lets the list hold any shape. */
const tool = <Shape extends z.ZodRawShape>(definition: AgentTool<Shape>) =>
  definition as unknown as AgentTool;

/** How long to wait for scenario tests or a simulation before saying it's still going. */
const WAIT_MS = 5 * 60_000;
const CHECK_EVERY_MS = 2_000;
const sleep = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

/** Polls until a background run finishes, or gives up and says to check again. */
async function waitFor(check: () => Promise<{ latest?: { status: string } | null }>) {
  const until = Date.now() + WAIT_MS;
  for (;;) {
    const state = await check();
    if (state.latest?.status !== "running") {
      return state;
    }
    if (Date.now() > until) {
      return { stillRunning: true, message: "It's still running. Check again in a minute." };
    }
    await sleep(CHECK_EVERY_MS);
  }
}

/** Saves a section or page, from the revision it's at now. */
async function save(client: TrumanClient, draftId: string, section: string, value: unknown) {
  const settings = await client.call<{
    sections: Record<string, { revision: number }>;
    pages: Record<string, { revision: number }>;
  }>("GET", `/admin/drafts/${draftId}/settings`);
  const page = section.startsWith("page:") ? section.slice("page:".length) : null;
  const baseRevision =
    (page ? settings.pages[page]?.revision : settings.sections[section]?.revision) ?? 0;
  return client.call("PUT", `/admin/drafts/${draftId}/settings`, { section, value, baseRevision });
}

