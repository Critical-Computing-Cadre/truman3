import {
  type EventPayload,
  type EventSource,
  type EventType,
  eventPayloadSchemas,
} from "@truman3/core";
import type { Database, Transaction } from "./client.ts";
import { events } from "./schema.ts";

export interface NewEvent<T extends EventType> {
  type: T;
  payload: EventPayload<T>;
  worldId: string;
  studyVersionId: string;
  source: EventSource;
  /** When it happened. For browser-reported events, this is the browser's clock. */
  occurredAt: Date;
  participantId?: string | null;
  conditionId?: string | null;
  actorId?: string | null;
  targetContentId?: string | null;
  targetActorId?: string | null;
  /** Generated by the browser per action. A repeat of the same ID is ignored. */
  clientEventId?: string | null;
}

/**
 * The one way events get written. Checks the payload against the catalog in core, so nothing
 * malformed reaches the log. Returns null if this was a repeat of an event already recorded.
 */
export async function recordEvent<T extends EventType>(
  db: Database | Transaction,
  event: NewEvent<T>,
): Promise<{ id: number } | null> {
  const payload = eventPayloadSchemas[event.type].parse(event.payload);

  const [row] = await db
    .insert(events)
    .values({ ...event, payload })
    .onConflictDoNothing({ target: [events.worldId, events.clientEventId] })
    .returning({ id: events.id });

  return row ?? null;
}
