import { randomUUID } from "node:crypto";
import { setUpTeam } from "@truman3/accounts";
import { schema } from "@truman3/db";
import { createTestDatabase } from "@truman3/db/testing";
import { createStorage, storageConfigFromEnv } from "@truman3/storage";
import { eq } from "drizzle-orm";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { createApp } from "../app.ts";

/** Personal access tokens, for agents working for a researcher, and what they can't do. ADR 64. */

let database: Awaited<ReturnType<typeof createTestDatabase>>;
let app: ReturnType<typeof createApp>;
const storage = createStorage(storageConfigFromEnv());

beforeAll(async () => {
  database = await createTestDatabase();
  await storage.ensureBucket();
  app = createApp({
    pingDatabase: database.ping,
    db: database.db,
    storage,
    mediaPublicUrl: "http://media.test",
    getClientIp: () => undefined,
    secureCookies: false,
  });
});

afterAll(async () => {
  storage.close();
  await database.destroy();
});

/** A researcher signed in to the admin app, with a cookie. */
async function researcher() {
  const id = randomUUID().slice(0, 8);
  const { teamId, password } = await setUpTeam(database.db, {
    teamName: `lab-${id}`,
    slug: `lab-${id}`,
    email: `${id}@example.edu`,
    name: "Owner",
  });
  const login = await app.request("/admin/login", {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ email: `${id}@example.edu`, password }),
  });
  const cookie = (login.headers.get("set-cookie") ?? "").split(";")[0] ?? "";
  const call = (method: string, url: string, body?: object) =>
    app.request(url, {
      method,
      headers: { "content-type": "application/json", cookie },
      ...(body ? { body: JSON.stringify(body) } : {}),
    });
  return { teamId, call };
}

/** Calls the API as an agent would, with only a token. */
const asAgent = (token: string) => (method: string, url: string, body?: object) =>
  app.request(url, {
    method,
    headers: { "content-type": "application/json", authorization: `Bearer ${token}` },
    ...(body ? { body: JSON.stringify(body) } : {}),
  });

describe("a personal access token", () => {
  it("is shown once, works like signing in, and stops when revoked", async () => {
    const owner = await researcher();
    const created = (await (
      await owner.call("POST", "/admin/tokens", { name: "Claude Code" })
    ).json()) as { id: string; token: string; name: string };
    expect(created.token).toMatch(/^truman_pat_/);

    const agent = asAgent(created.token);
    expect((await agent("GET", "/admin/me")).status).toBe(200);
    // It's listed without its value, and when it was last used.
    const { tokens } = (await (await owner.call("GET", "/admin/tokens")).json()) as {
      tokens: { id: string; lastUsedAt: string | null; token?: string }[];
    };
    expect(tokens).toEqual([expect.objectContaining({ id: created.id })]);
    expect(tokens[0]?.token).toBeUndefined();
    expect(tokens[0]?.lastUsedAt).not.toBeNull();

    expect((await owner.call("DELETE", `/admin/tokens/${created.id}`)).status).toBe(200);
    expect((await agent("GET", "/admin/me")).status).toBe(401);
    expect((await asAgent("truman_pat_madeup")("GET", "/admin/me")).status).toBe(401);
  });

  it("can start a study and write a draft, marked as generated by an agent", async () => {
    const owner = await researcher();
    const { token } = (await (
      await owner.call("POST", "/admin/tokens", { name: "Claude Code" })
    ).json()) as { token: string };
    const agent = asAgent(token);
    const started = await agent("POST", "/admin/studies", {
      teamId: owner.teamId,
      title: "From a brief",
      slug: `brief-${randomUUID().slice(0, 8)}`,
      assignment: "uniform",
      packId: null,
    });
    expect(started.status).toBe(200);
    const { draftId } = (await started.json()) as { draftId: string };
    const added = await agent("POST", `/admin/drafts/${draftId}/items`, {
      kind: "actor",
      fields: { username: "maya", name: "Maya" },
    });
    expect(added.status).toBe(200);
    const { id } = (await added.json()) as { id: string };
    const [item] = await database.db
      .select({ provenance: schema.draftItems.provenance })
      .from(schema.draftItems)
      .where(eq(schema.draftItems.id, id));
    expect(item?.provenance).toEqual({
      origin: "generated",
      detail: { by: "agent", token: "Claude Code" },
    });
  });

  it("can't do what reaches real participants, which is for a researcher to do", async () => {
    const owner = await researcher();
    const { token } = (await (
      await owner.call("POST", "/admin/tokens", { name: "Claude Code" })
    ).json()) as { token: string };
    const agent = asAgent(token);
    const someId = randomUUID();
    for (const [method, url] of [
      ["POST", `/admin/versions/${someId}/launch`],
      ["POST", `/admin/studies/${someId}/stop`],
      ["DELETE", `/admin/studies/${someId}`],
      ["POST", `/admin/studies/${someId}/withdraw`],
      ["GET", `/admin/studies/${someId}/export`],
      ["GET", `/admin/studies/${someId}/photos`],
      ["GET", "/admin/prolific"],
      ["POST", `/admin/studies/${someId}/prolific/approve`],
      ["POST", `/admin/studies/${someId}/christof/runs/${someId}`],
      ["POST", "/admin/tokens"],
      ["GET", "/api/admin/tokens"],
    ] as const) {
      const response = await agent(method, url, method === "GET" ? undefined : {});
      expect([method, url, response.status]).toEqual([method, url, 403]);
      expect(((await response.json()) as { error: string }).error).toContain("recommend");
    }
    // What isn't on that list still works.
    expect((await agent("GET", "/admin/studies")).status).toBe(200);
  });
});
